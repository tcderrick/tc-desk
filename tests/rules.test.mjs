import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, getDoc, setDoc, updateDoc, deleteDoc, writeBatch, collection, collectionGroup, query, where, getDocs } from 'firebase/firestore';
import { readFileSync } from 'fs';

const env = await initializeTestEnvironment({ projectId: 'demo-tcdesk', firestore: { rules: readFileSync('../firestore.rules', 'utf8'), host: '127.0.0.1', port: 8089 } });
const as = e => env.authenticatedContext(e.replace(/\W/g, '_'), { email: e, email_verified: true }).firestore();
const A = 'alice@example.com', B = 'bob@example.com', C = 'carol@example.com', D = 'dave@example.com', T = 'teammate@example.com', X = 'xavier@example.com';
const a = as(A), b = as(B), c = as(C), d = as(D), t = as(T), x = as(X);
await env.withSecurityRulesDisabled(async ctx => {
  const f = ctx.firestore();
  await setDoc(doc(f, 'logins', T), { name: 'Teammate' });
  await setDoc(doc(f, 'transactions', 'main1'), { f: { address: 'main deal' } });
});
let pass = 0, fail = 0;
const ok = async (name, p) => { try { await assertSucceeds(p); pass++; console.log('PASS', name) } catch (e) { fail++; console.log('FAIL (should allow)', name, e.message) } };
const no = async (name, p) => { try { await assertFails(p); pass++; console.log('PASS', name) } catch (e) { fail++; console.log('FAIL (should deny)', name, e.message) } };
const mk = (f, id, owner) => { const bt = writeBatch(f); bt.set(doc(f, 'ws', id), { owner, name: id, at: 1 }); bt.set(doc(f, 'wsmem', owner), { ws: id, role: 'owner', name: id, at: 1 }); return bt.commit(); };

await ok('alice creates her workspace', mk(a, 'w1', A));
await ok('carol creates her workspace', mk(c, 'w2', C));
await no('alice cannot create a second workspace', mk(a, 'w3', A));
await no('teammate on the main team cannot create a workspace', mk(t, 'w4', T));
await no('xavier cannot create a workspace owned by someone else', (() => { const bt = writeBatch(x); bt.set(doc(x, 'ws', 'w5'), { owner: B, name: 'n', at: 1 }); bt.set(doc(x, 'wsmem', X), { ws: 'w5', role: 'owner', name: 'n', at: 1 }); return bt.commit(); })());
await ok('alice writes a deal in her workspace', setDoc(doc(a, 'ws/w1/transactions', 'd1'), { f: { address: '1 Main' } }));
await ok('alice reads her deal', getDoc(doc(a, 'ws/w1/transactions', 'd1')));
await ok('alice saves her own views', setDoc(doc(a, 'ws/w1/data/users/u1', 'prefs'), { x: 1 }));
await no('carol cannot read alice deals', getDoc(doc(c, 'ws/w1/transactions', 'd1')));
await no('carol cannot write alice deals', setDoc(doc(c, 'ws/w1/transactions', 'd2'), { x: 1 }));
await no('bob cannot add himself to alice workspace', setDoc(doc(b, 'wsmem', B), { ws: 'w1', role: 'member', name: 'w1', at: 1 }));
await no('bob cannot make himself owner of alice workspace', setDoc(doc(b, 'wsmem', B), { ws: 'w1', role: 'owner', name: 'w1', at: 1 }));
await no('alice cannot read the main TC Desk', getDoc(doc(a, 'transactions', 'main1')));
await no('alice cannot write the main TC Desk', setDoc(doc(a, 'contacts', 'z'), { x: 1 }));
await ok('main teammate reads the main TC Desk', getDoc(doc(t, 'transactions', 'main1')));
await no('main teammate cannot read alice workspace', getDoc(doc(t, 'ws/w1/transactions', 'd1')));
await no('main teammate cannot read the ws record via the catch-all', getDoc(doc(t, 'ws', 'w1')));
await no('main teammate cannot write wsmem via the catch-all', setDoc(doc(t, 'wsmem', B), { ws: 'w1', role: 'member' }));
await no('alice cannot invite as a full member directly', setDoc(doc(a, 'wsmem', B), { ws: 'w1', role: 'member', name: 'w1', at: 1 }));
await ok('alice invites bob', setDoc(doc(a, 'wsmem', B), { ws: 'w1', role: 'invited', name: 'w1', at: 1 }));
await no('invited bob cannot read deals yet', getDoc(doc(b, 'ws/w1/transactions', 'd1')));
await ok('bob reads his invite', getDoc(doc(b, 'wsmem', B)));
await no('alice cannot promote bob herself', updateDoc(doc(a, 'wsmem', B), { role: 'member' }));
await ok('bob accepts the invite', setDoc(doc(b, 'wsmem', B), { ws: 'w1', role: 'member', name: 'w1', at: 2 }));
await ok('bob reads alice deals now', getDoc(doc(b, 'ws/w1/transactions', 'd1')));
await ok('bob edits a deal', setDoc(doc(b, 'ws/w1/transactions', 'd1'), { f: { address: '1 Main St' } }));
await no('bob (member) cannot invite others', setDoc(doc(b, 'wsmem', X), { ws: 'w1', role: 'invited', name: 'w1', at: 1 }));
await no('bob cannot move himself to carol workspace', setDoc(doc(b, 'wsmem', B), { ws: 'w2', role: 'member', name: 'w2', at: 3 }));
await no('alice cannot steal carol from her workspace', setDoc(doc(a, 'wsmem', C), { ws: 'w1', role: 'invited', name: 'w1', at: 1 }));
await no('alice cannot delete carol membership', deleteDoc(doc(a, 'wsmem', C)));
await ok('alice lists her team', getDocs(query(collection(a, 'wsmem'), where('ws', '==', 'w1'))));
await no('carol cannot list alice team', getDocs(query(collection(c, 'wsmem'), where('ws', '==', 'w1'))));
await no('alice cannot remove herself as owner', deleteDoc(doc(a, 'wsmem', A)));
await no('alice cannot hand ownership to carol', updateDoc(doc(a, 'ws', 'w1'), { owner: C }));
await no('member cannot rewrite the workspace record', setDoc(doc(as('m2@example.com'), 'ws', 'w1'), { owner: 'm2@example.com', name: 'x', at: 1 }));
await ok('alice renames her workspace', updateDoc(doc(a, 'ws', 'w1'), { name: 'Alice TC' }));
// Portal in a workspace
await ok('alice shares a file with dave', setDoc(doc(a, 'ws/w1/portal', 'p1'), { email: D, txId: 'd1', data: { show: { chat: true } } }));
await ok('alice shares a no-chat file with dave', setDoc(doc(a, 'ws/w1/portal', 'p2'), { email: D, txId: 'd9', data: { show: { chat: false } } }));
await ok('dave finds his files across workspaces', getDocs(query(collectionGroup(d, 'portal'), where('email', '==', D))));
await no('dave cannot list everyone portal files', getDocs(query(collectionGroup(d, 'portal'))));
await no('carol cannot read dave portal file', getDoc(doc(c, 'ws/w1/portal', 'p1')));
await ok('dave chats on his file', setDoc(doc(d, 'ws/w1/pchat', 'm1'), { email: D, from: 'client', text: 'hi', pid: 'p1', txId: 'd1', at: 1 }));
await no('dave cannot chat where chat is off', setDoc(doc(d, 'ws/w1/pchat', 'm2'), { email: D, from: 'client', text: 'hi', pid: 'p2', txId: 'd9', at: 1 }));
await no('dave cannot pose as the team', setDoc(doc(d, 'ws/w1/pchat', 'm3'), { email: D, from: 'team', text: 'hi', pid: 'p1', txId: 'd1', at: 1 }));
await ok('dave reads his chat', getDocs(query(collectionGroup(d, 'pchat'), where('email', '==', D))));
await no('dave cannot read deals', getDoc(doc(d, 'ws/w1/transactions', 'd1')));
await ok('alice reads dave chat in her workspace', getDocs(collection(a, 'ws/w1/pchat')));
await ok('bob leaves the team', deleteDoc(doc(b, 'wsmem', B)));
await no('bob cannot read deals after leaving', getDoc(doc(b, 'ws/w1/transactions', 'd1')));
console.log(`\n${pass} passed, ${fail} failed`);
await env.cleanup();
process.exit(fail ? 1 : 0);
